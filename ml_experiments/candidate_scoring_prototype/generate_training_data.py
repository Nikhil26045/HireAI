import numpy as np
import pandas as pd
from pathlib import Path


FEATURE_NAMES = [
    "skills_relevance",
    "relevant_experience",
    "education_relevance",
    "required_skills_matched",
    "missing_required_skills",
    "overall_jd_relevance",
    "interview_answer_relevance",
    "communication_assessment",
]


def calculate_rule_based_target(df: pd.DataFrame) -> pd.Series:
    """
    Computes ground-truth target according to the verified rule-based formula:
    - Resume (35%): 0.45*skills + 0.40*exp + 0.15*edu
    - Job Matching (35%): 0.40*req_matched + 0.20*(1 - missing_req) + 0.40*jd_rel
    - Interview (30%): 0.65*ans_rel + 0.35*comm
    Overall = 0.35*Resume + 0.35*Job + 0.30*Interview (scaled 0-100)
    """
    resume_score = 100.0 * (
        0.45 * df["skills_relevance"]
        + 0.40 * df["relevant_experience"]
        + 0.15 * df["education_relevance"]
    )
    job_score = 100.0 * (
        0.40 * df["required_skills_matched"]
        + 0.20 * (1.0 - df["missing_required_skills"])
        + 0.40 * df["overall_jd_relevance"]
    )
    interview_score = 100.0 * (
        0.65 * df["interview_answer_relevance"]
        + 0.35 * df["communication_assessment"]
    )
    overall = 0.35 * resume_score + 0.35 * job_score + 0.30 * interview_score
    return overall


def generate_training_data(n_samples: int = 5000, seed: int = 42) -> pd.DataFrame:
    """
    Generates 5,000 synthetic candidate rows:
    - ~90% (4,500 rows) correlated typical candidates using a latent capability distribution.
    - ~10% (500 rows) edge cases: all-zeros, all-ones, single-feature extremes, and contradictory pairs.
    """
    rng = np.random.default_rng(seed)

    n_edge = int(n_samples * 0.10)  # 500 edge cases
    n_typical = n_samples - n_edge   # 4500 correlated typical candidates

    # -------------------------------------------------------------
    # 1. Correlated Typical Candidates (4,500 rows)
    # -------------------------------------------------------------
    # Latent general ability factor
    latent_tech = rng.beta(2.5, 2.0, size=n_typical)   # Technical seniority
    latent_comm = rng.beta(3.0, 2.0, size=n_typical)   # Communication & academic

    # Resume features
    skills_rel = np.clip(0.7 * latent_tech + rng.normal(0, 0.12, n_typical), 0.0, 1.0)
    exp_rel = np.clip(0.8 * latent_tech + rng.normal(0, 0.14, n_typical), 0.0, 1.0)
    edu_rel = np.clip(0.6 * latent_comm + rng.normal(0, 0.18, n_typical), 0.0, 1.0)

    # Job matching features (strongly correlated with technical skills)
    req_matched = np.clip(0.85 * skills_rel + rng.normal(0, 0.10, n_typical), 0.0, 1.0)
    # missing_required_skills is inversely correlated with required_skills_matched
    missing_req = np.clip(1.0 - req_matched + rng.normal(0, 0.08, n_typical), 0.0, 1.0)
    jd_rel = np.clip(0.5 * skills_rel + 0.4 * exp_rel + rng.normal(0, 0.12, n_typical), 0.0, 1.0)

    # Interview features
    ans_rel = np.clip(0.6 * skills_rel + 0.3 * latent_comm + rng.normal(0, 0.12, n_typical), 0.0, 1.0)
    comm_assess = np.clip(0.8 * latent_comm + rng.normal(0, 0.12, n_typical), 0.0, 1.0)

    typical_data = {
        "skills_relevance": skills_rel,
        "relevant_experience": exp_rel,
        "education_relevance": edu_rel,
        "required_skills_matched": req_matched,
        "missing_required_skills": missing_req,
        "overall_jd_relevance": jd_rel,
        "interview_answer_relevance": ans_rel,
        "communication_assessment": comm_assess,
    }
    df_typical = pd.DataFrame(typical_data)

    # -------------------------------------------------------------
    # 2. Edge Cases (500 rows)
    # -------------------------------------------------------------
    edge_rows = []

    # 2a. All minimums (all zeros except missing_req which is worst-case 1.0) (50 rows)
    for _ in range(50):
        edge_rows.append({
            "skills_relevance": 0.0,
            "relevant_experience": 0.0,
            "education_relevance": 0.0,
            "required_skills_matched": 0.0,
            "missing_required_skills": 1.0,
            "overall_jd_relevance": 0.0,
            "interview_answer_relevance": 0.0,
            "communication_assessment": 0.0,
        })

    # 2b. All maximums (all ones except missing_req which is best-case 0.0) (50 rows)
    for _ in range(50):
        edge_rows.append({
            "skills_relevance": 1.0,
            "relevant_experience": 1.0,
            "education_relevance": 1.0,
            "required_skills_matched": 1.0,
            "missing_required_skills": 0.0,
            "overall_jd_relevance": 1.0,
            "interview_answer_relevance": 1.0,
            "communication_assessment": 1.0,
        })

    # 2c. Single-feature extremes (one feature at 1.0, rest at 0.0, or vice versa) (200 rows)
    for i in range(200):
        feat_idx = i % len(FEATURE_NAMES)
        row = {f: rng.uniform(0.1, 0.4) for f in FEATURE_NAMES}
        if i % 2 == 0:
            row[FEATURE_NAMES[feat_idx]] = 1.0
        else:
            row[FEATURE_NAMES[feat_idx]] = 0.0
        edge_rows.append(row)

    # 2d. Contradictory pairs: both required_skills_matched and missing_required_skills high (100 rows)
    for _ in range(100):
        row = {f: rng.uniform(0.3, 0.8) for f in FEATURE_NAMES}
        row["required_skills_matched"] = rng.uniform(0.80, 1.0)
        row["missing_required_skills"] = rng.uniform(0.80, 1.0)
        edge_rows.append(row)

    # 2e. Contradictory pairs: both required_skills_matched and missing_required_skills low (100 rows)
    for _ in range(100):
        row = {f: rng.uniform(0.3, 0.8) for f in FEATURE_NAMES}
        row["required_skills_matched"] = rng.uniform(0.0, 0.20)
        row["missing_required_skills"] = rng.uniform(0.0, 0.20)
        edge_rows.append(row)

    df_edge = pd.DataFrame(edge_rows)

    # Combine both sets
    df_combined = pd.concat([df_typical, df_edge], ignore_index=True)

    # Shuffle dataset
    df_combined = df_combined.sample(frac=1.0, random_state=seed).reset_index(drop=True)

    # Calculate rule-based target and add Gaussian noise (sd ≈ 3.0)
    rule_score = calculate_rule_based_target(df_combined)
    noise = rng.normal(loc=0.0, scale=3.0, size=len(df_combined))
    proxy_target = np.clip(rule_score + noise, 0.0, 100.0)

    df_combined["rule_based_score"] = rule_score.round(2)
    df_combined["overall_candidate_score_proxy"] = proxy_target.round(2)

    return df_combined


def main():
    output_dir = Path(__file__).resolve().parent
    output_csv = output_dir / "candidate_training_data.csv"

    print("=" * 70)
    print("HIREAI - GENERATING SYNTHETIC SCORING TRAINING DATA")
    print("Disclaimer: Target scores are synthetic proxy labels for pipeline validation.")
    print("=" * 70)

    df = generate_training_data(n_samples=5000, seed=42)
    df.to_csv(output_csv, index=False)

    print(f"Total rows generated: {len(df)}")
    print(f"Features included:    {FEATURE_NAMES}")
    print(f"Target column:        'overall_candidate_score_proxy'")
    print(f"Target mean:          {df['overall_candidate_score_proxy'].mean():.2f}")
    print(f"Target std:           {df['overall_candidate_score_proxy'].std():.2f}")
    print(f"Target min/max:       {df['overall_candidate_score_proxy'].min():.2f} / {df['overall_candidate_score_proxy'].max():.2f}")
    print(f"\nSaved training data to: {output_csv}")
    print("=" * 70)


if __name__ == "__main__":
    main()
